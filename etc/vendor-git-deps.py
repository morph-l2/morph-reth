#!/usr/bin/env python3
"""Regenerate vendor/ from the Cargo git dependencies pinned in Cargo.lock.

reth and discv5 are not published on crates.io, so Cargo.lock pins them as git
dependencies. Internal build hosts cannot reach GitHub: MakefileBuild.mk builds
with `--config vendor/cargo-config.toml`, which resolves those dependencies from
this directory. Plain cargo commands never load that file, so everyone else
keeps fetching them from GitHub.

Usage:
    make vendor                         # regenerate vendor/ in place
    etc/vendor-git-deps.py OUTPUT_DIR   # write the result elsewhere (CI)

Needs network access to GitHub and crates.io. The output depends on the cargo
version, which is recorded in vendor/TOOLCHAIN; CI regenerates with that
toolchain and fails if the result differs from the committed copy.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path
from urllib.parse import parse_qsl, urlsplit

ROOT = Path(__file__).resolve().parent.parent

# Paths that are not needed to build and that this repository should not
# redistribute, with the reason recorded in vendor/README.md.
STRIP = {
    "reth-mdbx-sys": {
        "libmdbx/ut_and_examples": "AGPL-3.0 example programs; build.rs only compiles mdbx.c",
    },
}

# The reth crates carry no license files of their own; the texts live at the
# root of the upstream repository, and redistributing the sources needs them.
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice)", re.IGNORECASE)

# Keys of a git source that select the reference.
GIT_REFS = ("branch", "tag", "rev")

CONFIG_HEADER = """\
# Generated by etc/vendor-git-deps.py; do not edit.
#
# Source replacement for internal builds, loaded explicitly by MakefileBuild.mk:
#     cargo build --config vendor/cargo-config.toml ...
# Plain cargo commands never read this file, so they keep fetching these git
# dependencies from GitHub.
#
# Relative paths in a --config file resolve against the parent of the directory
# holding it, so `vendor` below is <repo>/vendor wherever cargo runs from.
"""

README = """\
# vendor/

Sources of the Cargo **git** dependencies pinned in `Cargo.lock`, generated by
`etc/vendor-git-deps.py`. Do not edit by hand.

## Who uses it

Only `MakefileBuild.mk`. Internal build hosts cannot reach GitHub, so they
resolve these dependencies from here:

    cargo build --locked --config vendor/cargo-config.toml ...

Plain cargo commands never load `cargo-config.toml`: CI, Docker builds and
anyone building from GitHub keep fetching these dependencies from GitHub.
crates.io dependencies are not vendored.

## Updating

After changing a git dependency in `Cargo.toml` / `Cargo.lock`, run `make vendor`
on a host with GitHub access and commit the result.

- `MakefileBuild.mk` refuses to build when `SOURCES` does not match `Cargo.lock`.
  Cargo keeps no checksums for vendored git sources, so a stale copy would
  otherwise build without any error.
- The `Vendor` workflow regenerates this directory with the cargo version in
  `TOOLCHAIN` and fails on any difference.

## Layout

| Path | Contents |
|---|---|
| `<crate>/` | `cargo vendor` output for each git package |
| `SOURCES` | the `Cargo.lock` git sources, with commits, this copy was generated from |
| `cargo-config.toml` | the source replacement loaded by `MakefileBuild.mk` |
| `TOOLCHAIN` | the cargo version that generated this copy |
| `licenses/<owner>/<repo>/` | license files from the root of each upstream repository |

Removed from the vendored crates because they are not needed to build:

{stripped}

## Sources

{sources}
"""


def run(*cmd: str, capture: bool = True) -> str:
    result = subprocess.run(
        cmd,
        cwd=ROOT,
        check=True,
        text=True,
        stdout=subprocess.PIPE if capture else subprocess.DEVNULL,
    )
    return result.stdout or ""


def git_packages() -> dict[tuple[str, str], str]:
    """Map (name, version) to the Cargo.lock source of every git package."""
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text())
    return {
        (pkg["name"], pkg["version"]): pkg["source"]
        for pkg in lock["package"]
        if pkg.get("source", "").startswith("git+")
    }


def copy_git_packages(full: Path, out: Path, wanted: dict[tuple[str, str], str]) -> None:
    found = set()
    for crate in sorted(full.iterdir()):
        package = tomllib.loads((crate / "Cargo.toml").read_text())["package"]
        key = (package["name"], package["version"])
        if key in wanted:
            shutil.copytree(crate, out / crate.name, symlinks=True)
            found.add(key)
    if missing := sorted(set(wanted) - found):
        sys.exit(f"cargo vendor did not produce these git packages: {missing}")


def strip_paths(out: Path) -> list[str]:
    """Delete the STRIP paths and drop them from .cargo-checksum.json, which
    lists every file of a vendored crate and must stay consistent with it."""
    stripped = []
    for crate, paths in STRIP.items():
        checksum_file = out / crate / ".cargo-checksum.json"
        if not checksum_file.exists():
            continue
        checksums = json.loads(checksum_file.read_text())
        for rel, reason in paths.items():
            if not (out / crate / rel).is_dir():
                print(f"warning: {crate}/{rel} no longer exists; update STRIP", file=sys.stderr)
                continue
            shutil.rmtree(out / crate / rel)
            prefix = f"{rel}/"
            checksums["files"] = {
                path: digest for path, digest in checksums["files"].items() if not path.startswith(prefix)
            }
            stripped.append(f"- `{crate}/{rel}/`: {reason}")
        checksum_file.write_text(json.dumps(checksums, separators=(",", ":"), ensure_ascii=False))
    return stripped


def repo_slug(source: str) -> str:
    """`owner/repo` of a git source URL."""
    path = urlsplit(source.removeprefix("git+")).path.strip("/")
    return path.removesuffix(".git")


def copy_licenses(out: Path, sources: list[str]) -> None:
    """Copy the license files at the root of each upstream checkout."""
    metadata = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked"))
    roots: dict[str, Path] = {}
    for package in metadata["packages"]:
        source = package.get("source")
        if source in sources and source not in roots:
            root = Path(package["manifest_path"]).parent
            # Cargo checks out each git source as a full repository.
            while not (root / ".git").exists():
                if root == root.parent:
                    sys.exit(f"cannot find the checkout root of {source}")
                root = root.parent
            roots[source] = root
    for source in sources:
        texts = sorted(f for f in roots[source].iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
        if not texts:
            sys.exit(f"no license file at the root of {source}")
        dest = out / "licenses" / repo_slug(source)
        dest.mkdir(parents=True)
        for text in texts:
            shutil.copyfile(text, dest / text.name)


def cargo_config(sources: list[str]) -> str:
    lines = [CONFIG_HEADER]
    for source in sources:
        # [source] keys are the Cargo.lock source without the resolved commit.
        key = source.split("#", 1)[0]
        url = urlsplit(key.removeprefix("git+"))
        refs = dict(parse_qsl(url.query))
        lines.append(f"[source.{json.dumps(key)}]")
        lines.append(f"git = {json.dumps(url._replace(query='').geturl())}")
        lines.extend(f"{name} = {json.dumps(refs[name])}" for name in GIT_REFS if name in refs)
        lines.append('replace-with = "vendored-git"')
        lines.append("")
    lines.append("[source.vendored-git]")
    lines.append('directory = "vendor"')
    return "\n".join(lines) + "\n"


def install(staged: Path, out: Path) -> None:
    if out.exists():
        if not (out / "SOURCES").is_file():
            sys.exit(f"refusing to replace {out}: it is not a directory generated by this script")
        shutil.rmtree(out)
    shutil.move(staged, out)


def main() -> None:
    out = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "vendor"
    packages = git_packages()
    if not packages:
        sys.exit("Cargo.lock has no git dependencies; delete vendor/ instead")
    sources = sorted(set(packages.values()))
    toolchain = re.match(r"cargo (\S+)", run("cargo", "--version")).group(1)

    with tempfile.TemporaryDirectory(prefix="vendor-git-deps-") as tmp:
        full, staged = Path(tmp, "all"), Path(tmp, "vendor")
        # `cargo vendor` cannot filter by source, so vendor everything and keep
        # the git packages. crates.io packages stay with the registry (JFrog).
        run("cargo", "vendor", "--locked", "--quiet", str(full), capture=False)
        staged.mkdir()
        copy_git_packages(full, staged, packages)
        stripped = strip_paths(staged)
        copy_licenses(staged, sources)
        (staged / "SOURCES").write_text("".join(f'source = "{source}"\n' for source in sources))
        (staged / "cargo-config.toml").write_text(cargo_config(sources))
        (staged / "TOOLCHAIN").write_text(f"{toolchain}\n")
        (staged / "README.md").write_text(
            README.format(
                stripped="\n".join(stripped) or "- nothing",
                sources="\n".join(f"- `{source}`" for source in sources),
            )
        )
        install(staged, out)
    print(f"vendored {len(packages)} packages from {len(sources)} git sources into {out}")


if __name__ == "__main__":
    main()
